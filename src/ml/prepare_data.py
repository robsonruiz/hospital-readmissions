def load_calibrated_model():
    """
    Load the CatBoost + sigmoid calibrated model.
    """
    if not CALIBRATED_MODEL_PATH.exists():
        raise FileNotFoundError(
            f"\nCalibrated model not found:\n"
            f"{CALIBRATED_MODEL_PATH}\n\n"
            "Check the filename generated by "
            "calibration_analysis.py."
        )

    print(
        f"   Loading: "
        f"{CALIBRATED_MODEL_PATH.name}"
    )

    model = joblib.load(
        CALIBRATED_MODEL_PATH
    )

    if not hasattr(model, "predict_proba"):
        raise TypeError(
            "The calibrated model does not have "
            "'predict_proba'."
        )

    return model


def predict_calibrated_probability(model, X_valid):
    """
    Generate calibrated positive-class probabilities.
    """
    probability = model.predict_proba(
        X_valid
    )

    if probability.ndim != 2:
        raise ValueError(
            "predict_proba() did not return a 2D array."
        )

    if probability.shape[1] < 2:
        raise ValueError(
            "predict_proba() does not contain "
            "probabilities for two classes."
        )

    probability = probability[:, 1]

    if not np.isfinite(probability).all():
        raise ValueError(
            "Calibrated probabilities contain "
            "NaN or infinite values."
        )

    return probability


def calculate_metrics(
    y_true,
    probability,
    threshold,
):
    """
    Calculate classification metrics for one threshold.
    """
    prediction = (
        probability >= threshold
    ).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        prediction,
        labels=[0, 1],
    ).ravel()

    precision = precision_score(
        y_true,
        prediction,
        zero_division=0,
    )

    recall = recall_score(
        y_true,
        prediction,
        zero_division=0,
    )

    f1 = f1_score(
        y_true,
        prediction,
        zero_division=0,
    )

    accuracy = accuracy_score(
        y_true,
        prediction,
    )

    balanced_accuracy = balanced_accuracy_score(
        y_true,
        prediction,
    )

    specificity = (
        tn / (tn + fp)
        if (tn + fp) > 0
        else 0.0
    )

    return {
        "threshold": threshold,
        "precision": precision,
        "recall": recall,
        "specificity": specificity,
        "f1": f1,
        "accuracy": accuracy,
        "balanced_accuracy": balanced_accuracy,
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),
    }


def run_threshold_analysis(
    y_valid,
    probability,
):
    """
    Evaluate thresholds from 0.05 to 0.95
    with increments of 0.01.
    """
    thresholds = np.round(
        np.arange(
            0.05,
            0.951,
            0.01,
        ),
        2,
    )

    results = []

    for threshold in thresholds:
        metrics = calculate_metrics(
            y_valid,
            probability,
            threshold,
        )

        results.append(metrics)

    return pd.DataFrame(results)


def select_best_threshold(results_df):
    """
    Select the threshold with the highest F1.

    Tie-breakers:
    1. higher recall
    2. higher specificity
    """
    ranked = results_df.sort_values(
        by=[
            "f1",
            "recall",
            "specificity",
        ],
        ascending=[
            False,
            False,
            False,
        ],
    ).reset_index(drop=True)

    return ranked.iloc[0]


def save_results(
    results_df,
    best_result,
):
    """
    Save complete threshold analysis and
    best threshold.
    """
    MODELS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    results_df.to_csv(
        THRESHOLD_RESULTS_PATH,
        index=False,
    )

    best_df = pd.DataFrame(
        [best_result]
    )

    best_df.to_csv(
        BEST_THRESHOLD_PATH,
        index=False,
    )


